import test, { type TestContext } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { gitIn, makeWorkspace } from './support/git-workspace.ts';

/**
 * agctx and Microsoft APM in one repository. The markers come from apm-cli 0.30.0:
 * APM regenerates AGENTS.md or CLAUDE.md when its generated marker is one of the
 * first five lines, and in managed_section mode it replaces only the text between
 * <!-- apm:start --> and <!-- apm:end -->.
 */
const APM_AGENTS_HEADER = '<!-- Generated by APM CLI from .apm/ primitives -->';
const APM_CLAUDE_HEADER = '<!-- Generated by APM CLI -->';
const START = '<!-- apm:start -->';
const END = '<!-- apm:end -->';

const apmSection = (rules: string) => `${START}\n${APM_AGENTS_HEADER}\n<!-- Build ID: 0123456789ab -->\n\n${rules}\n${END}`;
const sectionOf = (text: string) => text.slice(text.indexOf(START), text.indexOf(END) + END.length);

/** What `apm compile` does in managed_section mode: replace only the text between the markers. */
function apmCompile(file: string, rules: string) {
  const content = fs.readFileSync(file, 'utf8');
  const start = content.indexOf(START);
  const end = content.indexOf(END);
  assert.ok(start >= 0 && end > start, 'the APM markers are still in place');
  fs.writeFileSync(file, content.slice(0, start) + apmSection(rules) + content.slice(end + END.length));
}

function setup(t: TestContext) {
  const { person, folder } = makeWorkspace(t, 'agctx-apm-');
  const me = person('me');
  me.ok(['profile', 'create', 'company', '--scope', 'company']);
  const repo = (name: string) => {
    const dir = folder(name);
    gitIn(dir, 'init', '--quiet', '--initial-branch=main');
    return dir;
  };
  return { me, repo };
}

test('an APM managed section in AGENTS.md survives agctx sync while both tools keep updating', t => {
  const { me, repo } = setup(t);
  const dir = repo('agctx-first');
  me.ok(['profile', 'apply', 'company', dir, '--yes']);
  const agents = path.join(dir, 'AGENTS.md');
  fs.appendFileSync(agents, `\n${START}\n${END}\n`);
  apmCompile(agents, '- APM-TEAM-T1: team rule');
  me.ok(['profile', 'sync', dir, '--yes']);
  apmCompile(agents, '- APM-TEAM-T1: team rule\n- APM-TEAM-T2: second team rule');
  const before = fs.readFileSync(agents, 'utf8');

  fs.appendFileSync(path.join(me.profileDir('company'), 'AGENTS.md'), '\n- COMPANY-C2: new company rule\n');
  me.ok(['profile', 'sync', dir, '--yes']);
  const after = fs.readFileSync(agents, 'utf8');
  assert.match(after, /COMPANY-C2/);
  assert.equal(sectionOf(after), sectionOf(before), 'agctx leaves the APM section byte for byte');
  assert.ok(after.indexOf('COMPANY-C2') < after.indexOf(START), 'the APM section stays in the project part below the profile');
  assert.equal(me.run(['check', dir]).status, 0, 'APM updates are outside the agctx managed area');
});

test('agctx stops before taking over an AGENTS.md or CLAUDE.md that APM regenerates in its default mode', t => {
  const { me, repo } = setup(t);
  const dir = repo('apm-first');
  const generated = `${APM_AGENTS_HEADER}\n<!-- Build ID: 0123456789ab -->\n\n# AGENTS.md\n\n- APM-TEAM-T1: team rule\n`;
  fs.writeFileSync(path.join(dir, 'AGENTS.md'), generated);

  const dryRun = me.run(['profile', 'apply', 'company', dir, '--dry-run']);
  assert.equal(dryRun.status, 2, dryRun.stdout + dryRun.stderr);
  assert.match(dryRun.stderr, /APM/);
  assert.match(dryRun.stderr, /managed_section/);
  const refused = me.run(['profile', 'apply', 'company', dir, '--yes', '--json']);
  assert.equal(refused.status, 2);
  assert.equal(JSON.parse(refused.stdout).errors[0].code, 'project.apm-generated');
  assert.equal(fs.readFileSync(path.join(dir, 'AGENTS.md'), 'utf8'), generated, 'nothing is written');
  assert.ok(!fs.existsSync(path.join(dir, 'agctx.project.json')));

  // The way out the hint describes: move the generated file aside, apply, then add the markers for managed_section.
  fs.renameSync(path.join(dir, 'AGENTS.md'), path.join(dir, 'AGENTS.apm-default.md'));
  me.ok(['profile', 'apply', 'company', dir, '--yes']);
  fs.appendFileSync(path.join(dir, 'AGENTS.md'), `\n${START}\n${END}\n`);
  apmCompile(path.join(dir, 'AGENTS.md'), '- APM-TEAM-T1: team rule');
  assert.equal(me.run(['profile', 'sync', dir, '--yes']).status, 0);
  assert.equal(me.run(['check', dir]).status, 0);

  const claudeDir = repo('apm-claude');
  fs.writeFileSync(path.join(claudeDir, 'CLAUDE.md'), `${APM_CLAUDE_HEADER}\n# CLAUDE.md\n\n- APM rule\n`);
  const claude = me.run(['profile', 'apply', 'company', claudeDir, '--yes']);
  assert.equal(claude.status, 2, claude.stdout + claude.stderr);
  assert.match(claude.stderr, /CLAUDE\.md/);
  assert.ok(!fs.existsSync(path.join(claudeDir, 'AGENTS.md')), 'nothing is written');
});

test('an APM marker further down the file is content, not ownership', t => {
  const { me, repo } = setup(t);
  const dir = repo('marker-below');
  fs.writeFileSync(path.join(dir, 'AGENTS.md'), `# Project\n\nNotes.\n\nMore notes.\n\nEven more.\n\n${APM_AGENTS_HEADER}\n`);
  me.ok(['profile', 'apply', 'company', dir, '--yes']);
});
